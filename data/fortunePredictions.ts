const STORAGE_KEY = 'svyazka_fortune_state';

interface FortuneState {
  date: string;
  accountId: string;
  predictionId: string;
}

export function getMoscowDayKey(): string {
  return new Intl.DateTimeFormat('sv-SE', {
    timeZone: 'Europe/Moscow',
    year: 'numeric', month: '2-digit', day: '2-digit',
  }).format(new Date());
}

function hashString(s: string): number {
  let h = 0;
  for (let i = 0; i < s.length; i++) {
    h = ((h << 5) - h + s.charCodeAt(i)) | 0;
  }
  return Math.abs(h);
}

export function getTodayFortune(accountId: string = 'anonymous'): FortunePrediction {
  const today = getMoscowDayKey();
  const key = `${STORAGE_KEY}_${accountId}`;
  try {
    const raw = localStorage.getItem(key);
    if (raw) {
      const state: FortuneState = JSON.parse(raw);
      if (state.date === today && state.accountId === accountId) {
        const found = FORTUNE_PREDICTIONS.find((p) => p.id === state.predictionId);
        if (found) return found;
      }
    }
  } catch { /* ignore */ }
  const seed = hashString(`${accountId}:${today}`);
  const prediction = FORTUNE_PREDICTIONS[seed % FORTUNE_PREDICTIONS.length];
  try {
    localStorage.setItem(key, JSON.stringify({ date: today, accountId, predictionId: prediction.id }));
  } catch { /* ignore */ }
  return prediction;
}
